"""FastAPI application serving live crop price forecasts.

Routes:

``GET  /``                 the web UI
``GET  /api/health``       liveness probe, never touches the model
``GET  /api/meta``         crops, markets, versions and the data range
``POST /api/predict``      next week's forecast, computed at request time
``GET  /api/history``      the real observed weekly prices for a series
``GET  /api/backtest``     the model re-run over recent weeks against the naive forecast
``GET  /api/model/{crop}`` the model card
``GET  /docs``             interactive API documentation, generated by FastAPI

Every data route computes its answer from the dataset and the registered model on disk.
If either is missing the app still starts and ``/api/health`` still answers, so a
deployment comes up and reports honestly rather than crash-looping.

Run with::

    uv run web-start
"""

from __future__ import annotations

import logging
from contextlib import asynccontextmanager
from pathlib import Path
from typing import Any

from fastapi import FastAPI, HTTPException, Query, Request
from fastapi.responses import HTMLResponse, JSONResponse
from fastapi.staticfiles import StaticFiles
from fastapi.templating import Jinja2Templates
from pydantic import BaseModel, Field

from app.service import SERVICE, DataUnavailable, UnknownCrop, UnknownMarket
from automl import __version__
from automl.config import setup_logging

LOGGER = logging.getLogger(__name__)

HERE = Path(__file__).resolve().parent
TEMPLATES = Jinja2Templates(directory=str(HERE / "templates"))


@asynccontextmanager
async def lifespan(_: FastAPI):
    """Log what the service can see at boot, without failing if data is absent.

    Args:
        _: The application, unused.

    Yields:
        Control back to the server for the lifetime of the process.
    """
    setup_logging()
    try:
        meta = SERVICE.meta()
        LOGGER.info(
            "ready: %d crops, data %s..%s",
            len(meta["crops"]),
            meta["data_start"],
            meta["data_end"],
        )
    except DataUnavailable as error:
        LOGGER.warning("starting without data or models: %s", error)
    yield


app = FastAPI(
    lifespan=lifespan,
    title="Mandi crop price forecaster",
    version=__version__,
    description=(
        "Weekly wholesale price forecasts for Indian crops, from a LightGBM model "
        "tuned by a hand-written Bayesian optimizer. Every number is computed live "
        "from the processed dataset."
    ),
    docs_url="/docs",
)

static_dir = HERE / "static"
static_dir.mkdir(exist_ok=True)
app.mount("/static", StaticFiles(directory=str(static_dir)), name="static")


class PredictRequest(BaseModel):
    """Body of a forecast request."""

    crop: str = Field(..., description="Crop name or slug, e.g. 'Onion'")
    market: str = Field(..., description="Market name, e.g. 'Maharashtra'")


def _unavailable(error: Exception) -> JSONResponse:
    """Render a 503 for a missing dataset or registry.

    Args:
        error: The raised error.

    Returns:
        A JSON response explaining how to fix it.
    """
    return JSONResponse(
        status_code=503,
        content={
            "error": "data or models not available",
            "detail": str(error),
            "fix": [
                "uv run python -m automl.data.fetch",
                "uv run python -m automl.data.aggregate",
                "uv run python -m automl.registry",
            ],
        },
    )


@app.get("/api/health")
def health() -> dict[str, Any]:
    """Liveness probe.

    Returns:
        Service status, and whether data and models are loadable.
    """
    status: dict[str, Any] = {"status": "ok", "version": __version__}
    try:
        meta = SERVICE.meta()
        status["models_loaded"] = True
        status["crops"] = [crop["crop"] for crop in meta["crops"]]
    except Exception as error:  # noqa: BLE001 - health must never raise
        status["models_loaded"] = False
        status["detail"] = str(error)
    return status


@app.get("/api/meta")
def meta() -> Any:
    """Describe the crops, markets and data range the UI should offer.

    Returns:
        The metadata payload, or 503 when nothing is registered yet.
    """
    try:
        return SERVICE.meta()
    except DataUnavailable as error:
        return _unavailable(error)


@app.post("/api/predict")
def predict(body: PredictRequest) -> Any:
    """Forecast next week's price for one crop in one market.

    Args:
        body: The crop and market to forecast.

    Returns:
        The forecast, computed at request time.

    Raises:
        HTTPException: 400 for an unknown crop or market.
    """
    try:
        return SERVICE.predict(body.crop, body.market)
    except DataUnavailable as error:
        return _unavailable(error)
    except (UnknownCrop, UnknownMarket) as error:
        raise HTTPException(status_code=400, detail=str(error)) from error


@app.get("/api/history")
def history(
    crop: str = Query(..., description="Crop name or slug"),
    market: str = Query(..., description="Market name"),
    weeks: int = Query(104, ge=4, le=500, description="How many recent weeks"),
) -> Any:
    """Return the real observed weekly prices for one series.

    Args:
        crop: Crop name or slug.
        market: Market name.
        weeks: How many recent weeks to return.

    Returns:
        Week and price pairs, oldest first.

    Raises:
        HTTPException: 400 for an unknown crop or market.
    """
    try:
        return SERVICE.history(crop, market, weeks)
    except DataUnavailable as error:
        return _unavailable(error)
    except (UnknownCrop, UnknownMarket) as error:
        raise HTTPException(status_code=400, detail=str(error)) from error


@app.get("/api/backtest")
def backtest(
    crop: str = Query(..., description="Crop name or slug"),
    market: str = Query(..., description="Market name"),
    weeks: int = Query(26, ge=4, le=200, description="How many recent weeks to score"),
) -> Any:
    """Re-run the model over recent weeks and compare it against the naive forecast.

    Args:
        crop: Crop name or slug.
        market: Market name.
        weeks: How many recent weeks to score.

    Returns:
        Per-week actual and predicted prices plus summary metrics.

    Raises:
        HTTPException: 400 for an unknown crop or market.
    """
    try:
        return SERVICE.backtest(crop, market, weeks)
    except DataUnavailable as error:
        return _unavailable(error)
    except (UnknownCrop, UnknownMarket) as error:
        raise HTTPException(status_code=400, detail=str(error)) from error


@app.get("/api/model/{crop}")
def model_card(crop: str) -> Any:
    """Expose one crop's model card.

    Args:
        crop: Crop name or slug.

    Returns:
        The card as JSON.

    Raises:
        HTTPException: 400 for an unknown crop.
    """
    try:
        return SERVICE.card(crop)
    except DataUnavailable as error:
        return _unavailable(error)
    except UnknownCrop as error:
        raise HTTPException(status_code=400, detail=str(error)) from error


@app.get("/", response_class=HTMLResponse)
def index(request: Request) -> Any:
    """Serve the web UI.

    Args:
        request: The incoming request, needed by Jinja2's FastAPI integration.

    Returns:
        The rendered page. All data is fetched by the page itself from ``/api/*``.
    """
    return TEMPLATES.TemplateResponse(request, "index.html", {"version": __version__})
